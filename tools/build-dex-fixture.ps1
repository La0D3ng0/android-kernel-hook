param(
    [string]$SdkPath = "",
    [int]$Api = 35,
    [string]$OutputDex = "",
    [string]$OutputInclude = "",
    [ValidateRange(0, 50000)]
    [int]$PaddingMethods = 0
)

$ErrorActionPreference = 'Stop'
$projectDirectory = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($SdkPath)) {
    if (-not [string]::IsNullOrWhiteSpace($env:ANDROID_HOME)) {
        $SdkPath = $env:ANDROID_HOME
    } elseif (-not [string]::IsNullOrWhiteSpace($env:ANDROID_SDK_ROOT)) {
        $SdkPath = $env:ANDROID_SDK_ROOT
    } else {
        $SdkPath = Join-Path $env:LOCALAPPDATA 'Android\Sdk'
    }
}
if ([string]::IsNullOrWhiteSpace($OutputDex)) {
    $OutputDex = Join-Path $projectDirectory 'tests\dex-fixture\rtgum-dex-fixture.dex'
}
if ([string]::IsNullOrWhiteSpace($OutputInclude)) {
    $OutputInclude = Join-Path $projectDirectory 'tests\dex-fixture\rtgum-dex-fixture.inc'
}

$buildTools = Get-ChildItem (Join-Path $SdkPath 'build-tools') -Directory |
    Sort-Object { [version]$_.Name } -Descending | Select-Object -First 1
if ($null -eq $buildTools) { throw "no Android build-tools under $SdkPath" }
$d8 = Join-Path $buildTools.FullName 'd8.bat'
$androidJar = Join-Path $SdkPath "platforms\android-$Api\android.jar"
$javac = (Get-Command javac.exe -ErrorAction SilentlyContinue).Source
foreach ($required in @($d8, $androidJar)) {
    if (-not (Test-Path -LiteralPath $required -PathType Leaf)) {
        throw "required tool missing: $required"
    }
}
if ([string]::IsNullOrWhiteSpace($javac)) { throw 'javac.exe not found on PATH' }

$work = Join-Path $projectDirectory 'out\dex-fixture'
$classes = Join-Path $work 'classes'
$dexDirectory = Join-Path $work 'dex'
$generatedRoot = Join-Path $work 'generated-src'
Remove-Item -LiteralPath $classes, $dexDirectory, $generatedRoot `
    -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $classes, $dexDirectory | Out-Null
$sources = @(Get-ChildItem (Join-Path $projectDirectory 'tests\dex-fixture\src') `
    -Recurse -Filter '*.java' | ForEach-Object FullName)
if ($sources.Count -eq 0) { throw 'DEX fixture has no Java sources' }

# Optional generated padding crosses allocator chunk boundaries without
# checking thousands of uninteresting Java sources into the repository. D8
# does not shrink in this build, so every method remains in the test DEX.
if ($PaddingMethods -gt 0) {
    $generatedDirectory = Join-Path $work 'generated-src\dev\rtgum\dex'
    New-Item -ItemType Directory -Force -Path $generatedDirectory | Out-Null
    $paddingSource = Join-Path $generatedDirectory 'FixturePadding.java'
    $writer = [System.IO.StreamWriter]::new(
        $paddingSource, $false, [System.Text.UTF8Encoding]::new($false))
    try {
        $writer.WriteLine('package dev.rtgum.dex;')
        $writer.WriteLine('final class FixturePadding {')
        for ($index = 0; $index -lt $PaddingMethods; ++$index) {
            $writer.WriteLine("  static int m$index() { return $index; }")
        }
        $writer.WriteLine('}')
    } finally {
        $writer.Dispose()
    }
    $sources += $paddingSource
}

$oldPreference = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
& $javac -source 8 -target 8 -Xlint:-options -bootclasspath $androidJar `
    -classpath $androidJar -nowarn -d $classes $sources 2>$null
$javacExit = $LASTEXITCODE
$ErrorActionPreference = $oldPreference
if ($javacExit -ne 0) { throw "DEX fixture javac failed ($javacExit)" }

$classFiles = @(Get-ChildItem $classes -Recurse -Filter '*.class' |
    ForEach-Object FullName)
$d8Api = [Math]::Min($Api, 34)
$oldPreference = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
& $d8 --release --min-api $d8Api --lib $androidJar --output $dexDirectory $classFiles 2>$null
$d8Exit = $LASTEXITCODE
$ErrorActionPreference = $oldPreference
if ($d8Exit -ne 0) { throw "DEX fixture d8 failed ($d8Exit)" }

$builtDex = Join-Path $dexDirectory 'classes.dex'
if (-not (Test-Path -LiteralPath $builtDex -PathType Leaf)) {
    throw 'd8 did not emit classes.dex'
}
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutputDex), `
    (Split-Path -Parent $OutputInclude) | Out-Null
Copy-Item -LiteralPath $builtDex -Destination $OutputDex -Force
$bytes = [System.IO.File]::ReadAllBytes($OutputDex)
if ($bytes.Length -lt 112 -or [System.Text.Encoding]::ASCII.GetString($bytes, 0, 4) -ne "dex`n") {
    throw 'generated payload is not a standard DEX image'
}

$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('/* Generated by tools/build-dex-fixture.ps1. */')
[void]$builder.AppendLine('static const unsigned char kRtgumDexFixture[] = {')
for ($index = 0; $index -lt $bytes.Length; $index += 12) {
    [void]$builder.Append('    ')
    $limit = [Math]::Min($index + 12, $bytes.Length)
    for ($cursor = $index; $cursor -lt $limit; ++$cursor) {
        [void]$builder.Append(('0x{0:x2},' -f $bytes[$cursor]))
        if ($cursor + 1 -lt $limit) { [void]$builder.Append(' ') }
    }
    [void]$builder.AppendLine()
}
[void]$builder.AppendLine('};')
[void]$builder.AppendLine("static constexpr unsigned long kRtgumDexFixtureSize = $($bytes.Length)UL;")
[System.IO.File]::WriteAllText($OutputInclude, $builder.ToString(),
    [System.Text.UTF8Encoding]::new($false))

$hash = (Get-FileHash -LiteralPath $OutputDex -Algorithm SHA256).Hash.ToLowerInvariant()
Write-Output "dex-fixture size=$($bytes.Length) sha256=$hash"
Write-Output "include=$OutputInclude"
Write-Output 'dex-fixture PASS'
